const {test,expect}=require('@playwright/test');
const {installCarePolishFixture}=require('./fixtures/care-polish-fixture');
async function openEditor(page,baseURL){
  await page.setViewportSize({width:390,height:844});
  await page.goto(`${baseURL}/directory.html?saveRecoveryFixture=1`,{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.documentElement.dataset.waffleUiReady==='true');
  await page.locator('#directory-grid [data-open-directory-profile]').click();
  const card=page.locator('.directory-card.is-profile-active');
  await expect(card.locator('[data-care-brief-medication]')).toHaveText('Give with dinner.');
  await page.waitForFunction(()=>window.__polishPendingProfileReads?.()===0);
  await card.locator('.directory-care-more-actions > summary').click();
  await card.locator('[data-care-brief-action="edit"]').click();
  const toggle=card.locator('[data-profile-subtab="foodWalks"]');
  if(await toggle.getAttribute('aria-expanded')!=='true')await toggle.click();
  await card.locator('[data-intake-attribute="foodAmount"]').fill('2 cups');
  return card;
}
test('confirmed save has an identity-scoped read-only recovery; rejection keeps a usable draft',async({page,baseURL})=>{
  const state=await installCarePolishFixture(page);
  const card=await openEditor(page,baseURL);
  const save=card.locator('[data-save-belongings]');
  let status=card.locator('[data-directory-profile-edit-status]');
  state.rejectSave=true;
  await save.click();
  await expect(status).toContainText('Synthetic save rejected');
  await expect(card).toHaveClass(/is-profile-editing/);
  await expect(card.locator('[data-intake-attribute="foodAmount"]')).toHaveValue('2 cups');
  await expect(save).toBeEnabled();
  state.rejectSave=false;
  await page.evaluate(()=>window.__failAfterSaveRefresh=true);
  await save.click();
  status=card.locator('[data-care-save-recovery]');
  await expect(status).toContainText('Your changes were saved. Some shared details could not be refreshed.');
  await expect(card).not.toHaveClass(/is-profile-editing/);
  await expect(card.locator('[data-care-change-category-count="foodWalks"]')).toBeHidden();
  const retry=status.getByRole('button',{name:'Retry refresh'});
  await expect(retry).toBeVisible();
  await page.waitForFunction(()=>window.__polishPendingProfileReads()===0);
  expect((await retry.boundingBox()).height).toBeGreaterThanOrEqual(44);
  const writes=state.writes.length;
  const profileReads=state.reads.filter(x=>x==='get_guest_profile').length;
  const belongingsReads=state.reads.filter(x=>x==='get_guest_belongings').length;
  state.failRead=true;
  await retry.click();
  await expect(status).toContainText('The refresh is still unavailable');
  await expect(retry).toBeEnabled();
  state.failRead=false;
  await retry.click();
  await expect(status).toContainText('Care details refreshed');
  await expect(retry).toHaveCount(0);
  await expect(status).toBeFocused();
  await expect(card.locator('[data-intake-attribute="foodAmount"]')).toHaveValue('2 cups');
  expect(state.writes).toHaveLength(writes);
  expect(state.reads.filter(x=>x==='get_guest_profile').length-profileReads).toBe(2);
  expect(state.reads.filter(x=>x==='get_guest_belongings').length-belongingsReads).toBe(0);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
});
test('changing stable dog identity prevents an old refresh action from issuing a read',async({page,baseURL})=>{
  const state=await installCarePolishFixture(page);
  const card=await openEditor(page,baseURL);
  await page.evaluate(()=>window.__failAfterSaveRefresh=true);
  await card.locator('[data-save-belongings]').click();
  const retry=card.getByRole('button',{name:'Retry refresh'});
  await expect(retry).toBeVisible();
  const before=await page.evaluate(()=>window.__recoveryRefreshAttempts||0);
  await card.evaluate(node=>node.dataset.directoryDogId='22222222-2222-4222-8222-222222222222');
  await retry.click();
  // Other page revalidation may independently respond to the identity change;
  // this old action must never enter the actual refresh/read function.
  expect(await page.evaluate(()=>window.__recoveryRefreshAttempts||0)).toBe(before);
  expect(state.writes).toHaveLength(1);
});
